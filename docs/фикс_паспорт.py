def diagnose(text: str) -> None:
    print("\n=== ДИАГНОСТИКА ===")

    # 1. Окрестность ## 7
    marker = "## 7. Доказательства и подтверждение способностей"
    n = text.count(marker)
    print(f"\n[6.6] вхождений '{marker}': {n}")
    if n >= 1:
        i = text.find(marker)
        snippet = text[max(0, i - 150):i + len(marker)]
        print("repr фрагмента перед '## 7':")
        print(repr(snippet))

    # 2. Все вхождения | 0.3.3 |
    print("\n[0.3.3] вхождения '| 0.3.3 | 31.10.2026 |':")
    v033_prefix = "| 0.3.3 | 31.10.2026 |"
    n = text.count(v033_prefix)
    print(f"найдено: {n}")
    idx = 0
    for line_no, line in enumerate(text.splitlines(), 1):
        if v033_prefix in line:
            print(f"  строка {line_no}: {line[:120]}{'...' if len(line) > 120 else ''}")

    # 3. Полная история
    print("\nИстория документа (все версии):")
    in_history = False
    for line_no, line in enumerate(text.splitlines(), 1):
        if line.strip() == "## История документа":
            in_history = True
            continue
        if in_history and line.startswith("## "):
            break
        if in_history and line.startswith("| 0."):
            print(f"  строка {line_no}: {line[:100]}{'...' if len(line) > 100 else ''}")


def fix_v033(text: str) -> tuple:
    """Спец-обработчик истории v0.3.3 + добавление v0.3.4."""
    n = text.count(V033_BLOCK)
    if n == 0:
        # уже есть v0.3.4, но нет v0.3.3
        if V034_BLOCK in text:
            return text, [("0.3", "уже было: v0.3.4 в истории")], []
        return text, [], [("0.3", "не найден ни v0.3.3, ни v0.3.4")]

    if n == 1:
        # единственное вхождение — просто добавим v0.3.4 после него
        new = text.replace(V033_BLOCK, V033_BLOCK + "\n" + V034_BLOCK, 1)
        return new, [("0.3", "v0.3.3 (1 вхождение) + v0.3.4 добавлен")], []

    if n == 2:
        # дубль: убираем второй, добавляем v0.3.4 после первого
        # найдём позицию первого, заменим первое на v0.3.3 + v0.3.4,
        # а второе — на пустоту (удаляем строку вместе с \n)
        first = text.find(V033_BLOCK)
        after_first = first + len(V033_BLOCK)
        before = text[:after_first]
        rest = text[after_first:]
        # в rest заменим оставшееся вхождение на пустую строку
        # аккуратно: удалим вместе с переводом строки перед или после
        if rest.startswith("\n") and rest[len("\n"):].startswith(V033_BLOCK):
            # дубль идёт сразу после, через \n
            rest = rest[1 + len(V033_BLOCK):]
        elif V033_BLOCK in rest:
            # дубль где-то дальше
            idx = rest.find(V033_BLOCK)
            # удалим строку с дублем и предшествующий \n
            if idx > 0 and rest[idx-1] == "\n":
                rest = rest[:idx-1] + rest[idx + len(V033_BLOCK):]
            else:
                rest = rest[:idx] + rest[idx + len(V033_BLOCK):]
        new = before + "\n" + V034_BLOCK + rest
        return new, [("0.3", "удалён дубль v0.3.3 + добавлен v0.3.4")], []

    return text, [], [("0.3", f"найдено {n} вхождений v0.3.3 — не трогаю, требуется ручная проверка")]


def fix_6_6(text: str) -> tuple:
    """Спец-обработчик вставки 6.6 перед '## 7. Доказательства...'."""
    if "### 6.6. Ширина и глубина" in text:
        return text, [("6.6", "уже было")], []

    marker = "## 7. Доказательства и подтверждение способностей"
    n = marker and text.count(marker)
    if n == 0:
        return text, [], [("6.6", "не найден '## 7. Доказательства...'")]
    if n > 1:
        return text, [], [("6.6", f"'## 7. Доказательства...' встречается {n} раз")]

    new = text.replace(marker, SECTION_6_6 + marker, 1)
    return new, [("6.6", "вставлен перед '## 7'")], []


def main() -> int:
    if not PASSPORT.exists():
        print(f"ОШИБКА: не найден {PASSPORT.resolve()}")
        return 1

    original = PASSPORT.read_text(encoding="utf-8").replace("\r\n", "\n")

    if DIAGNOSE:
        diagnose(original)
        return 0

    text = original
    applied = []
    skipped = []
    already_done = []

    # --- Спец-обработчики ---
    text, ok_6_6, err_6_6 = fix_6_6(text)
    applied += ok_6_6
    skipped += err_6_6

    text, ok_033, err_033 = fix_v033(text)
    applied += ok_033
    skipped += err_033

    # --- Обычные правки ---
    for fix in NORMAL_FIXES:
        tag = fix["id"]
        desc = fix["description"]
        search = fix["search"]
        replace = fix["replace"]

        n = text.count(search)
        if n == 0:
            if text.count(replace) > 0:
                already_done.append((tag, desc))
            else:
                skipped.append((tag, desc, "search не найден"))
            continue
        if n > 1:
            skipped.append((tag, desc, f"search не уникален ({n} раз)"))
            continue

        text = text.replace(search, replace, 1)
        applied.append((tag, desc))

    if text == original:
        print("Нет изменений.")
        if already_done:
            print(f"\nУже было: {len(already_done)}")
            for tag, desc in already_done:
                print(f"   [{tag}] {desc}")
        if skipped:
            print(f"\nПропущено: {len(skipped)}")
            for tag, desc, reason in skipped:
                print(f"   [{tag}] {desc} — {reason}")
        return 0 if not skipped else 1

    print(f"Применено: {len(applied)} / уже было: {len(already_done)} / пропущено: {len(skipped)}")

    if applied:
        print("\n✓ Применено:")
        for tag, desc in applied:
            print(f"   [{tag}] {desc}")

    if already_done:
        print("\n• Уже было:")
        for tag, desc in already_done:
            print(f"   [{tag}] {desc}")

    if skipped:
        print("\n✗ Пропущено:")
        for tag, desc, reason in skipped:
            print(f"   [{tag}] {desc} — {reason}")

    if DRY_RUN:
        print("\n[dry-run] Ничего не записано.")
        return 0

    if not NO_BACKUP:
        backup = PASSPORT.with_suffix(PASSPORT.suffix + ".bak")
        shutil.copy2(PASSPORT, backup)
        print(f"\nРезервная копия: {backup.resolve()}")

    PASSPORT.write_text(text, encoding="utf-8")
    print(f"Записан:        {PASSPORT.resolve()}")

    return 0 if not skipped else 1


if __name__ == "__main__":
    sys.exit(main())